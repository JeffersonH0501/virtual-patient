import {Dialog} from '../common/Dialog';
import {FC, ReactNode, useState} from 'react';
import {FileText} from 'lucide-react';

import {useTranslation} from 'react-i18next';
import {EvaluationCondition, EvaluationResult} from '../../types/evaluation';
import {useEvaluationAspects} from '../../contexts/EvaluationAspectsContext';
import {getAspectDisplayName} from './helpers/evaluation';
import {CaseDetailsDialog} from '../ClinicalCases/CaseDetailsDialog';
import {SubmittedHypothesesDialog} from './SubmittedHypothesesDialog';
import {EvaluationPromptCall, getEvaluationRuns} from '../../services/evaluations/evaluationRuns';
import {requestLearningMoments} from '../../services/evaluations/learningMoments';

type EvaluationCriteriaTooltipProps = {
  aspect: string;
  condition?: EvaluationCondition;
  isVisible: boolean;
  onClose: () => void;
  comparison?: ReactNode;
  interviewId?: number;
  result?: EvaluationResult;
  showPrompt?: boolean;
};

export const EvaluationCriteriaTooltip: FC<EvaluationCriteriaTooltipProps> = ({
  aspect,
  isVisible,
  onClose,
  comparison,
  interviewId,
  result,
  showPrompt = true,
  condition = 'TEXT_ONLY',
}) => {
  const {t} = useTranslation();
  const {aspects, multimodalAspects, error} = useEvaluationAspects();
  const [caseDetailsOpen, setCaseDetailsOpen] = useState(false);
  const [hypothesesOpen, setHypothesesOpen] = useState(false);
  const [promptOpen, setPromptOpen] = useState(false);
  const [promptLoading, setPromptLoading] = useState(false);
  const [promptError, setPromptError] = useState(false);
  const [promptCalls, setPromptCalls] = useState<EvaluationPromptCall[]>([]);
  const [learningPromptCalls, setLearningPromptCalls] = useState<EvaluationPromptCall[]>([]);
  const [learningPromptWasGenerated, setLearningPromptWasGenerated] = useState(false);
  const [savedSystemPrompts, setSavedSystemPrompts] = useState<string[]>([]);
  const dialogContainerId = `evaluation-criteria-${aspect}`;
  // Learning moments only exist for the multimodal condition and for the
  // categories enriched with multimodal evidence (interest, empathy, clarity).
  const metadata = multimodalAspects.find((entry) => entry.aspect === aspect);
  const showsLearningMoments = condition === 'TEXT_PLUS_MULTIMODAL' && metadata !== undefined;

  const loadPrompt = async () => {
    if (interviewId === undefined || !result) return;
    setPromptOpen(true);
    setPromptLoading(true);
    setPromptError(false);
    setPromptCalls([]);
    setLearningPromptCalls([]);
    setLearningPromptWasGenerated(false);
    setSavedSystemPrompts([]);
    try {
      const [runsResult, learningResult] = await Promise.allSettled([
        getEvaluationRuns(interviewId),
        showsLearningMoments ? requestLearningMoments(interviewId) : Promise.resolve(undefined),
      ]);
      if (showsLearningMoments && learningResult.status === 'fulfilled' && learningResult.value) {
        setLearningPromptWasGenerated(learningResult.value.status === 'completed');
        // Each category is generated by its own call (learning_moments_<category>).
        setLearningPromptCalls((learningResult.value.providerProvenance ?? [])
          .filter((entry) => entry.aspect === `learning_moments_${aspect}` && entry.promptMessages?.length)
          .map((entry) => ({aspect: entry.aspect, promptMessages: entry.promptMessages})));
      }
      if (runsResult.status === 'rejected') throw runsResult.reason;
      const runs = runsResult.value;
      const latestRun = (selectedCondition: EvaluationCondition) => runs
        .filter((entry) => entry.condition === selectedCondition)
        .sort((left, right) => right.createdAt.localeCompare(left.createdAt))[0];
      const multimodalCategory = multimodalAspects.some((entry) => entry.aspect === aspect);
      const run = latestRun(condition);
      const availableAspects = run?.snapshot.inputs?.availableAspects;
      const resultWasEnriched = Array.isArray(availableAspects)
        ? availableAspects.includes(aspect) : multimodalCategory;
      const textRun = condition === 'TEXT_PLUS_MULTIMODAL'
        ? latestRun('TEXT_ONLY') : undefined;
      // A multimodal category has a scoring call and a second call that writes the comment (`<aspect>_feedback`).
      const matchesAspect = (entry: EvaluationPromptCall) => aspect === 'completeness'
        ? entry.aspect.startsWith('completeness_') : entry.aspect === aspect || entry.aspect === `${aspect}_feedback`;
      let calls: EvaluationPromptCall[] = [];
      if (condition === 'TEXT_PLUS_MULTIMODAL' && resultWasEnriched) {
        const fallbackCalls = run?.snapshot.inputs?.fallbackPromptMessages ?? textRun?.snapshot.providerResponses ?? [];
        const textPromptHashes = new Set(fallbackCalls
          .map((entry) => entry.systemPromptSha256).filter(Boolean));
        calls = (run?.snapshot.providerResponses ?? []).filter((entry) =>
          matchesAspect(entry) && !textPromptHashes.has(entry.systemPromptSha256),
        );
      } else if (condition === 'TEXT_PLUS_MULTIMODAL') {
        calls = (textRun?.snapshot.providerResponses ?? []).filter(matchesAspect);
        if (!calls.some((entry) => entry.promptMessages?.length)) {
          calls = (run?.snapshot.inputs?.fallbackPromptMessages ?? []).filter(matchesAspect);
        }
      } else {
        calls = (run?.snapshot.providerResponses ?? []).filter(matchesAspect);
      }
      const callsWithMessages = calls.filter((entry) => (entry.promptMessages?.length ?? 0) > 0) as EvaluationPromptCall[];
      setPromptCalls(callsWithMessages);
      if (callsWithMessages.length === 0) {
        const prompts = {
          ...run?.snapshot.inputs?.fallbackPrompts,
          ...textRun?.snapshot.inputs?.prompts,
          ...run?.snapshot.inputs?.prompts,
        };
        const keys = aspect === 'completeness'
          ? ['completeness', 'completeness_verification', 'hypothesis_completeness']
          : [aspect];
        setSavedSystemPrompts(keys.flatMap((key) => prompts[key] ? [prompts[key]] : []));
      }
    } catch {
      setPromptError(true);
    } finally {
      setPromptLoading(false);
    }
  };

  // Convert snake_case aspect to camelCase for API response
  const getAspectKey = (aspectName: string) => {
    switch (aspectName) {
      case 'general_communication':
        return 'generalCommunication';
      case 'show_interest':
        return 'showInterest';
      case 'show_empathy':
        return 'showEmpathy';
      case 'speak_clearly':
        return 'speakClearly';
      case 'open_communication':
        return 'openCommunication';
      case 'completeness':
        return 'completeness';
      default:
        return aspectName;
    }
  };

  return (
    <Dialog
      title={t('evaluation.evaluationCriteria')}
      open={isVisible}
      onClose={onClose}
      size="medium"
      containerId={dialogContainerId}
      headerAction={showPrompt && interviewId !== undefined && result ? <button type="button"
        className="ui-icon-button" aria-label={t('evaluation.viewPrompt')} title={t('evaluation.viewPrompt')}
        aria-haspopup="dialog" onClick={() => void loadPrompt()}><FileText aria-hidden="true" /></button> : undefined}
    >
      {error || !aspects ? (
        <div className="text-center py-inset">
          <p className="text-danger-600 default-text">{t('evaluation.aspectsLoadError')}</p>
        </div>
      ) : (
        <>
          <div>
            <p className="text-neutral-600 default-text">
              {t('evaluation.evaluationBasedOn', {component: getAspectDisplayName(aspect, t)})}
            </p>
            {aspect === 'completeness' && interviewId !== undefined && <div className="mt-layout flex flex-wrap items-center gap-layout">
              <button type="button" className="ui-action-text underline secondary-text" onClick={() => setCaseDetailsOpen(true)}>{t('grading.viewFullClinicalCase')}</button>
              <button type="button" className="ui-action-text underline secondary-text" onClick={() => setHypothesesOpen(true)}>{t('grading.viewSubmittedHypotheses')}</button>
            </div>}
            <ol className="dialog-list mt-layout text-neutral-700 default-text">
              {(condition === 'TEXT_PLUS_MULTIMODAL' && metadata
                ? metadata.criteria
                : (aspects as any)[getAspectKey(aspect)]
              )?.map((criterion: string, criterionIndex: number) => (
                <li key={criterionIndex}>
                  <span>{criterion}</span>
                </li>
              ))}
            </ol>
          </div>
        </>
      )}
      {comparison && (
        <section className="dialog-reading-section">
          <h3 className="default-title">{t('evaluation.clinicalCaseComparison')}</h3>
          {comparison}
        </section>
      )}
      <aside className="dialog-annotation">
          <p className="mb-[var(--layout-gap-small)] font-semibold">{t('evaluation.criteriaBuiltFrom')}</p>
          <ul className="dialog-list secondary-text">
            <li>Communication Assessment Tool (CAT)</li>
            <li>Escala de Habilidades de Comunicación (EHC)</li>
            <li>Stanford Trust in Physician Scale</li>
            <li>Medical Interview Satisfaction Scale</li>
            <li>Patient-doctor relationship questionnaire (PDRQ-9) in primary care</li>
          </ul>
      </aside>
      {caseDetailsOpen && interviewId !== undefined && <CaseDetailsDialog interviewId={interviewId} containerId={dialogContainerId} onClose={() => setCaseDetailsOpen(false)} />}
      {hypothesesOpen && interviewId !== undefined && <SubmittedHypothesesDialog interviewId={interviewId} containerId={dialogContainerId} onClose={() => setHypothesesOpen(false)} />}
      <Dialog title={t('evaluation.fullPrompt')} open={promptOpen} onClose={() => setPromptOpen(false)}
        size="wide" containerId={dialogContainerId}>
        {promptLoading ? <p className="default-text">{t('common.loading')}</p> : promptError ?
          <p role="alert" className="text-danger-600 default-text">{t('errors.generic')}</p> : promptCalls.length > 0 ?
            <div className="space-y-layout">
              {promptCalls.map((call, callIndex) => <section key={callIndex}>
                <h3 className="mb-layout font-semibold secondary-text">{call.aspect.startsWith('completeness_')
                  ? t('evaluation.promptCall.' + call.aspect, {defaultValue: call.aspect})
                  : t(call.aspect.endsWith('_feedback') ? 'evaluation.promptCall.categoryFeedback' : 'evaluation.promptCall.category',
                    {component: getAspectDisplayName(call.aspect.replace(/_feedback$/, ''), t)})}</h3>
                <div className="grid grid-cols-1 gap-layout lg:grid-cols-2">
                  {call.promptMessages?.map((message, messageIndex) => <div key={messageIndex} className="min-w-0">
                    <h4 className="font-semibold secondary-text">{t('evaluation.promptRole.' + message.role, {defaultValue: message.role})}</h4>
                    <pre className="mt-[var(--layout-gap-small)] max-h-[60vh] overflow-auto whitespace-pre-wrap break-words rounded-card border border-border bg-surface p-inset default-text">{typeof message.content === 'string' ? message.content : JSON.stringify(message.content, null, 2)}</pre>
                  </div>)}
                </div>
              </section>)}
            </div> : savedSystemPrompts.length > 0 ? <>
              <p className="mb-layout text-warning-700 secondary-text">{t('evaluation.promptHistoryPartial')}</p>
              <div className="grid grid-cols-1 gap-layout lg:grid-cols-2">
                <section>
                  <h3 className="font-semibold secondary-text">{t('evaluation.promptRole.system')}</h3>
                  {savedSystemPrompts.map((prompt, index) => <pre key={index} className="mt-[var(--layout-gap-small)] max-h-[60vh] overflow-auto whitespace-pre-wrap break-words rounded-card border border-border bg-surface p-inset default-text">{prompt}</pre>)}
                </section>
                <section>
                  <h3 className="font-semibold secondary-text">{t('evaluation.promptRole.human')}</h3>
                  <p className="mt-[var(--layout-gap-small)] secondary-text">{t('evaluation.promptMessageNotCaptured')}</p>
                </section>
              </div>
            </> : <p className="default-text">{t('evaluation.promptUnavailable')}</p>}
        {/* Learning moments only exist in the multimodal condition for criteria with multimodal evidence; hide the section elsewhere. */}
        {showsLearningMoments && (learningPromptCalls.length > 0 ? <section className="border-t border-border pt-layout">
          <h3 className="mb-layout font-semibold secondary-text">{t('evaluation.promptCall.learningMoments')}</h3>
          {learningPromptCalls.map((call, callIndex) => <div key={callIndex} className="mb-layout grid grid-cols-1 gap-layout lg:grid-cols-2">
            {call.promptMessages?.map((message, messageIndex) => <div key={messageIndex} className="min-w-0">
              <h4 className="font-semibold secondary-text">{t('evaluation.promptRole.' + message.role, {defaultValue: message.role})}</h4>
              <pre className="mt-[var(--layout-gap-small)] max-h-[60vh] overflow-auto whitespace-pre-wrap break-words rounded-card border border-border bg-surface p-inset default-text">{typeof message.content === 'string' ? message.content : JSON.stringify(message.content, null, 2)}</pre>
            </div>)}
          </div>)}
        </section> : learningPromptWasGenerated && <p className="border-t border-border pt-layout secondary-text">{t('evaluation.learningMomentsPromptNotCaptured')}</p>)}
      </Dialog>
    </Dialog>
  );
};
